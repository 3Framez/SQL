SELECT UPPER(ENAME) AS NAME, LENGTH(ENAME) AS "LENGTH OF NAME"
FROM EMP

SELECT ENAME, CONCAT(CONCAT(SUBSTR(JOB, 0,3), '-'),SUBSTR(JOB, -3)) AS "JOBS"
FROM EMP


SELECT ENAME, CONCAT('HIRED ON ', TO_CHAR(HIREDATE, 'DD-Month-YYYY')) AS "DATE OF HIRE"   --TO_CHAR WORK ON DATES, NUMBERS, AND STRINGS. Converts each to datatype to its given format. TO_DATE converts a character to date
FROM EMP


--rounding to the nearest 1000 (-3) [800 -> 1000, 1250 -> 1000] and truncating to the nearest 100 (-2) [950 -> 900, 2975 -> 2900]
SELECT SAL, ROUND(SAL, 3), ROUND(SAL, -3), TRUNC(SAL, -2)  
FROM EMP

SELECT REPLACE(ENAME, 'A', '@') AS "EN@MAE" --REPLACE() REPLACES CHARACTERS
FROM EMP

SELECT DEPTNO, AVG(SAL) AS "AVERAGE SALARY", MAX(SAL) AS "MAXIMUM SLALRY", MIN(SAL) AS "MINIMUM SALARY" 
FROM EMP
GROUP BY DEPTNO

SELECT DEPTNO, AVG(SAL) AS "AVAERAGE SALARY"
