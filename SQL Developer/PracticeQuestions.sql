HAVING AVG(SAL) > 2000 

--TOTAL NUMBER OF EMPLOYEES HIRED AT THE BEGINNING OF EACH YEAR 
SELECT COUNT(*) AS "NUMBER OF EMPLOYEES HIRED", TRUNC(HIREDATE, 'YEAR') AS "DATE OF HIRE"
FROM EMP 
GROUP BY TRUNC(HIREDATE, 'YEAR')
ORDER BY 2

