-- CREATE EMP TABLE 

CREATE TABLE "EMP" (
    "EMPNO"    NUMBER(4, 0)
        GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 90000 INCREMENT BY 10 START WITH 8000 NOCACHE NOORDER NOCYCLE NOKEEP
        NOSCALE
        NOT NULL ENABLE,
    "ENAME"    VARCHAR2(50),
    "JOB"      VARCHAR2(50),
    "MGR"      NUMBER(4, 0),
    "HIREDATE" DATE,
    "SAL"      NUMBER(7, 2),
    "COMM"     NUMBER(7, 2),
    "DEPTNO"   NUMBER(4, 0),
    CONSTRAINT "EMP_PK" PRIMARY KEY ( "EMPNO" )
        USING INDEX enable
);


